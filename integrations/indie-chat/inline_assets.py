"""Put the shared Swiss stylesheet, the Inter font and the shared meeting views
(meetings.css, meetings.js: the list and a meeting, as in the phone web app)
into the indie-recorder app.

The app runs in a sandboxed frame of brainbot:agent command and loads nothing
from the box, so it carries them inline. Run this after changing any of them
in recorder/static/, and commit the result:

    python3 integrations/indie-chat/inline_assets.py
"""
import base64
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "integrations" / "indie-chat" / "indie-recorder.html"
STATIC = ROOT / "recorder" / "static"
NOTICE = ("/* Generated by integrations/indie-chat/inline_assets.py from recorder/static/swiss.css: edit that file, not this block.\n"
          "   Inter 4.1, (c) 2016 The Inter Project Authors, SIL Open Font License 1.1 (recorder/static/Inter-OFL.txt). */\n")


def main():
    css = (STATIC / "swiss.css").read_text()
    font = base64.b64encode((STATIC / "Inter.woff2").read_bytes()).decode()
    assert css.count('url("Inter.woff2")') == 1, "swiss.css must name Inter.woff2 once"
    css = css.replace('url("Inter.woff2")', f'url(data:font/woff2;base64,{font})')
    html = APP.read_text()
    html, n = re.subn(r'<style id="swiss">.*?</style>', lambda _: f'<style id="swiss">\n{NOTICE}{css}</style>', html, flags=re.S)
    assert n == 1, 'the app needs exactly one <style id="swiss"> block'
    for tag, name in (("style", "meetings.css"), ("script", "meetings.js")):
        body = (STATIC / name).read_text()
        note = f"/* Generated by integrations/indie-chat/inline_assets.py from recorder/static/{name}: edit that file, not this block. */\n"
        html, n = re.subn(rf'<{tag} id="meetings">.*?</{tag}>', lambda _: f'<{tag} id="meetings">\n{note}{body}</{tag}>', html, flags=re.S)
        assert n == 1, f'the app needs exactly one <{tag} id="meetings"> block'
    APP.write_text(html)
    print(f"{APP.relative_to(ROOT)}: {len(html.encode()) // 1024} KB")


if __name__ == "__main__":
    main()
